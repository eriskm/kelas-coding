"""Salin seluruh data servisku.db (SQLite) ke PostgreSQL (DATABASE_URL).

Pakai:
    set DATABASE_URL=postgresql+psycopg://<user>:<pass>@<host>:5432/<db>
    python migrate_sqlite_to_postgres.py

Idempoten: tabel yang sudah berisi baris dilewati (tidak ada duplikasi).
Skema dibuat dulu via Base.metadata.create_all, lalu sequence disesuaikan.
"""
import json
import os
import sqlite3
import sys
from datetime import date, datetime

from sqlalchemy import insert, inspect, text
from sqlalchemy import JSON as SAJSON

from database import Base, DB_PATH, SQLALCHEMY_DATABASE_URL, engine as pg_engine
import models  # noqa: F401  (registrasi seluruh tabel ke Base.metadata)

# Urutan = urutan dependensi FK (induk sebelum anak).
TABLE_ORDER = [
    "users",
    "customers",
    "service_orders",
    "payments",
    "warranty_claims",
    "status_history",
    "auth_tokens",
    "expenses",
    "kas_periods",
    "spareparts",
    "kas_entries",
]


def _row_to_dict(row, json_cols):
    d = {k: row[k] for k in row.keys()}
    for col in json_cols:
        v = d.get(col)
        if isinstance(v, str):
            try:
                d[col] = json.loads(v)
            except ValueError:
                d[col] = None
    return d


def main():
    if SQLALCHEMY_DATABASE_URL.startswith("sqlite"):
        sys.exit("DATABASE_URL belum diset ke PostgreSQL — batal (app tetap SQLite).")

    sqlite_path = os.environ.get("SQLITE_PATH") or DB_PATH
    if not os.path.isfile(sqlite_path):
        sys.exit("SQLite tidak ditemukan: %s" % sqlite_path)

    missing = set(TABLE_ORDER) ^ set(Base.metadata.tables)
    if missing:
        sys.exit("Daftar tabel tidak sinkron dengan models.py: %s" % sorted(missing))

    print("[1] Membuat skema PostgreSQL (create_all)...")
    Base.metadata.create_all(bind=pg_engine)

    src = sqlite3.connect("file:%s?mode=ro" % sqlite_path, uri=True)
    src.row_factory = sqlite3.Row

    copied = 0
    with pg_engine.begin() as conn:
        for table_name in TABLE_ORDER:
            table = Base.metadata.tables[table_name]
            cols = [c.name for c in table.columns]
            json_cols = [c.name for c in table.columns if isinstance(c.type, SAJSON)]
            rows = src.execute(
                "SELECT %s FROM %s" % (", ".join(cols), table_name)
            ).fetchall()
            n_target = conn.execute(
                text("SELECT count(*) FROM %s" % table_name)
            ).scalar() or 0
            if not rows:
                print("   %-18s sumber kosong" % table_name)
                continue
            if n_target:
                print("   %-18s DILEWATI (target sudah %d baris)" % (table_name, n_target))
                continue
            data = [_row_to_dict(r, json_cols) for r in rows]
            conn.execute(insert(table), data)
            copied += len(data)
            print("   %-18s %d baris OK" % (table_name, len(data)))
    src.close()

    print("[2] Menyesuaikan sequence/identity primary key...")
    with pg_engine.begin() as conn:
        for table_name in TABLE_ORDER:
            table = Base.metadata.tables[table_name]
            pk = list(table.primary_key.columns)[0].name
            info = conn.execute(text(
                "SELECT is_identity, column_default FROM information_schema.columns "
                "WHERE table_schema = 'public' AND table_name = :t AND column_name = :c"
            ), {"t": table_name, "c": pk}).first()
            has_seq = bool(info and (info[0] == "YES" or (info[1] and "nextval" in info[1])))
            if not has_seq:
                conn.execute(text(
                    "ALTER TABLE %s ALTER COLUMN %s ADD GENERATED BY DEFAULT AS IDENTITY"
                    % (table_name, pk)
                ))
                print("   %-18s + identity" % table_name)
            conn.execute(text(
                "SELECT setval(pg_get_serial_sequence('%(t)s', '%(c)s'), "
                "GREATEST(COALESCE((SELECT MAX(%(c)s) FROM %(t)s), 0), 1), "
                "(SELECT MAX(%(c)s) IS NOT NULL FROM %(t)s))" % {"t": table_name, "c": pk}
            ))

    print("[3] Verifikasi hasil...")
    inspector = inspect(pg_engine)
    with pg_engine.connect() as conn:
        for table_name in TABLE_ORDER:
            n = conn.execute(text("SELECT count(*) FROM %s" % table_name)).scalar()
            print("   %-18s %d baris" % (table_name, n))
    print("Selesai: %d baris disalin dari %s" % (copied, sqlite_path))


if __name__ == "__main__":
    main()
